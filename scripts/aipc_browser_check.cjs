'use strict';
// Real Chromium + HTTP checks. No model outputs or device telemetry are mocked.
const {chromium}=require('playwright');
const fs=require('fs');
const assert=require('node:assert/strict');
const base=process.argv[2]||'http://127.0.0.1:8765';
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||(process.platform==='linux'?'/usr/bin/chromium':undefined),args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1500,height:1050}});
  const failures=[];page.on('pageerror',error=>failures.push(error.message));let checks=0;
  const check=(value,message)=>{assert.ok(value,message);checks++;};
  try{
    await page.goto(base+'/?next=aipc');
    await page.locator('#username').fill('aipc-browser-test');
    await page.locator('#password').fill('Synthetic-browser-password-4826');
    await page.locator('#loginForm button').click();
    await page.waitForURL('**/aipc');
    await page.waitForFunction(()=>document.querySelector('#aipcCase')?.options.length===12);
    check(await page.locator('#aipcTurns .source-turn').count()>0,'original turns rendered');
    await page.locator('#runBaseline').click();
    await page.waitForFunction(()=>document.querySelector('#aipcResultState').textContent==='草稿待人工覆核');
    check((await page.locator('#aipcMetrics').innerText()).includes('lexical_section_baseline'),'explicit baseline source');
    check((await page.locator('#aipcMetrics').innerText()).includes('未執行語言模型'),'no simulated LLM');
    check((await page.locator('#aipcMetrics').innerText()).includes('待目標機驗證'),'no inferred NPU execution');
    check((await page.locator('#aipcMissing').innerText()).includes('必要欄位已提供'),'complete intake');
    await page.locator('.evidence-card button').first().click();
    check(await page.locator('.source-turn.selected').count()===1,'quote returns to source');
    const response=await page.request.get(base+await page.locator('#exportAIPC').getAttribute('href'));
    check(response.ok(),'real exported record');
    const record=await response.json();
    check(record.evidence.every(e=>e.quote_verified),'full turn quote validation');
    check(record.paired_imaging_case_id===null,'no cross-patient merge');
    check(record.automatically_saved_to_medical_report===false,'draft remains separate');
    await page.screenshot({path:'evidence/aipc_workstation_desktop.png',fullPage:true});
    await page.locator('#aipcCase').selectOption('synthetic-02');
    await page.waitForFunction(()=>document.querySelector('#aipcCaseCode').textContent==='synthetic-02'&&!document.querySelector('#runBaseline').disabled);
    check(await page.locator('#exportAIPC').getAttribute('aria-disabled')==='true','case switch clears export');
    await page.locator('#runBaseline').click();
    await page.waitForFunction(()=>document.querySelector('#aipcMissing').textContent.includes('待補：用藥核對'));
    check(true,'missing-medication path');
    await page.locator('#aipcCase').selectOption('synthetic-08');
    await page.waitForFunction(()=>document.querySelector('#aipcCaseCode').textContent==='synthetic-08'&&!document.querySelector('#runBaseline').disabled);
    await page.locator('#runBaseline').click();
    await page.waitForFunction(()=>document.querySelector('#aipcMissing').textContent.includes('待補：急性旗標'));
    check(true,'unknown acute remains unknown');
    await page.locator('#aipcCase').selectOption('synthetic-07');
    await page.waitForFunction(()=>document.querySelector('#aipcCaseCode').textContent==='synthetic-07'&&!document.querySelector('#runLocalLLM').disabled);
    await page.locator('#runLocalLLM').click();
    await page.waitForFunction(()=>document.querySelector('#aipcResultState').textContent==='急性旗標優先');
    check((await page.locator('#aipcMetrics').innerText()).includes('explicit_acute_flag_rules'),'acute bypasses model');
    await page.locator('#aipcSplit').selectOption('test_1');
    await page.waitForFunction(()=>document.querySelector('#aipcCase')?.options.length===200&&!document.querySelector('#runBaseline').disabled);
    check((await page.locator('#aipcMissing').innerText()).includes('沒有結構交接欄位'),'research text does not invent structured intake');
    await page.locator('#runBaseline').click();
    await page.waitForFunction(()=>document.querySelector('#aipcResultState').textContent==='草稿待人工覆核');
    check((await page.locator('#aipcSource').innerText()).includes('無病人配對'),'separate dataset provenance');
    await page.setViewportSize({width:780,height:1080});
    await page.screenshot({path:'evidence/aipc_workstation_compact.png',fullPage:true});
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no compact horizontal overflow');
    check(failures.length===0,'no browser script errors: '+failures.join('; '));
    fs.writeFileSync('evidence/aipc_browser_results.json',JSON.stringify({checks,passed:true,real_chromium:true,real_http:true,llm_executed:false,npu_executed:false},null,2));
    console.log(JSON.stringify({checks,passed:true,real_chromium:true,real_http:true,llm_executed:false,npu_executed:false}));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
